// gen_defs.mjs - generate cpp/ui_defs.h (UI metadata tables) from the web
// app's own definitions (js/defs.js) + repo file metadata (demos/).
// Run from repo root:  node android-native/host/gen_defs.mjs
// Output is COMMITTED (ui_defs.h) so the Android build needs no node.
import { writeFileSync, readdirSync } from 'node:fs';
import { INSTRUMENTS, DEVICES, FX_GROUPS, DRUM_PADS, PRESETS, INST_LIST } from '../../js/defs.js';

const esc = (s) => String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"');
const num = (v) => {
  if (typeof v !== 'number' || !isFinite(v)) return '0';
  return Number.isInteger(v) ? String(v) : String(Math.round(v * 1e6) / 1e6);
};
function paramLine(p) {
  const items = p.items ? p.items.map(esc).join('|') : '';
  return `    { "${esc(p.n)}", ${num(p.min)}, ${num(p.max)}, ${num(p.def)}, ${num(p.step || 0)}, ${p.curve === 'log' ? 1 : 0}, "${items}" }`;
}
function table(varName, src) {
  let out = `inline const UnitDef ${varName}[] = {\n`;
  for (const [type, d] of Object.entries(src)) {
    out += `  { ${type}, "${esc(d.name)}", {\n`;
    out += (d.params || []).map(paramLine).join(',\n');
    out += `\n  } },\n`;
  }
  return out + '};\n';
}

let h = `// ui_defs.h - GENERATED by host/gen_defs.mjs from js/defs.js (+ demos/ listing).
// UI metadata only: names + parameter schemas. Parameter ORDER matches the
// C++ engine (defs.js contract). Do not edit by hand - regenerate.
#pragma once
#include <string>
#include <vector>

namespace mdnative {
namespace defs {

struct ParamDef {
  const char* name; double min, max, def; double step; int logCurve; const char* items; // items: '|' separated, for step/list params
};
struct UnitDef {
  int type; const char* name; std::vector<ParamDef> params;
};

`;
h += table('kInstruments', INSTRUMENTS);
h += '\n';
h += table('kDevices', DEVICES);
h += '\ninline const int kInstList[] = { ' + INST_LIST.join(', ') + ' };\n';

h += '\nstruct FxGroup { const char* name; std::vector<int> types; };\ninline const FxGroup kFxGroups[] = {\n';
for (const [, name, types] of FX_GROUPS) h += `  { "${esc(name)}", { ${types.join(', ')} } },\n`;
h += '};\n';

h += '\nstruct PadDef { int pitch; const char* name; };\ninline const PadDef kDrumPads[] = {\n';
for (const p of DRUM_PADS) h += `  { ${p.pitch}, "${esc(p.name)}" },\n`;
h += '};\n';

// Presets: sparse param overrides, encoded "idx=val;idx=val"
h += '\nstruct PresetDef { int type; const char* cat; const char* name; const char* vals; };\ninline const PresetDef kPresets[] = {\n';
for (const [type, list] of Object.entries(PRESETS))
  for (const pr of list) {
    const vals = Object.entries(pr.p || {}).map(([k, v]) => `${k}=${num(v)}`).join(';');
    h += `  { ${type}, "${esc(pr.cat || '')}", "${esc(pr.name)}", "${vals}" },\n`;
  }
h += '};\n';

// Sample / SoundFont / demo file names found in the repo (metadata only -
// the native text protocol cannot upload sample bytes; see report).
const names = (dir, ext) => {
  try { return readdirSync(new URL('../../' + dir, import.meta.url)).filter((f) => f.toLowerCase().endsWith(ext)); }
  catch { return []; }
};
const sampleNames = names('demos/Samples', '.wav');
const sfNames = names('demos/SoundFonts', '.sf2');
const demoNames = names('demos', '.mdaw');
h += '\ninline const char* kSampleFiles[] = {\n';
for (const f of sampleNames) h += `  "${esc(f)}",\n`;
h += '  nullptr\n};\ninline const int kSampleFileCount = ' + sampleNames.length + ';\ninline const char* kSoundFontFiles[] = {\n';
for (const f of sfNames) h += `  "${esc(f)}",\n`;
h += '  nullptr\n};\ninline const int kSoundFontFileCount = ' + sfNames.length + ';\ninline const char* kDemoProjects[] = {\n';
for (const f of demoNames) h += `  "${esc(f)}",\n`;
h += '  nullptr\n};\ninline const int kDemoProjectCount = ' + demoNames.length + ';\n';

h += '\n}  // namespace defs\n}  // namespace mdnative\n';
const out = new URL('../app/src/main/cpp/ui_defs.h', import.meta.url);
writeFileSync(out, h);
console.log('wrote ui_defs.h', h.length, 'bytes');
